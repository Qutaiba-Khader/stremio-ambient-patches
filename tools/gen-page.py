#!/usr/bin/env python3
"""Writes Page.java from extensions/extension/page/page.html (the page is edited as HTML; the extension serves the string).
   tools/gen-page.py          write it
   tools/gen-page.py --check  exit 1 when Page.java is not what page.html gives"""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "extensions/extension/page/page.html").read_text(encoding="utf-8")
out = root / "extensions/extension/src/main/java/app/subsense/ambient/Page.java"
lines = html.split("\n")
parts = [json.dumps(l + "\n", ensure_ascii=True) for l in lines[:-1]] + ([json.dumps(lines[-1], ensure_ascii=True)] if lines[-1] else [])
# Java string literals: JSON escapes are valid Java escapes; long pages are joined at class load (a constant over 64 KB fails)
body = "\n            + ".join(parts)
java = f"""package app.subsense.ambient;

/** The settings page. Generated by tools/gen-page.py from extensions/extension/page/page.html - edit that file. */
final class Page {{
    private Page() {{}}

    static final String HTML = String.join("",
            {body.replace(chr(10) + '            + ', ',' + chr(10) + '            ')});
}}
"""
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text(encoding="utf-8") == java else 1)
out.write_text(java, encoding="utf-8")
print(f"{out.relative_to(root)}: {len(html)} characters")
